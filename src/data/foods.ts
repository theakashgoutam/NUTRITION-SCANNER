export function findFoodInDatabase(queryName: string): FoodItemData | undefined {
  const clean = queryName.toLowerCase().trim();
  
  // Exact name or ID match
  const directMatch = INDIAN_FOODS_DATABASE.find(
    f => f.id === clean || f.name.toLowerCase() === clean
  );
  if (directMatch) return directMatch;

  // Tag match
  const tagMatch = INDIAN_FOODS_DATABASE.find(f =>
    f.tags.some(t => clean === t || clean.includes(t) || t.includes(clean))
  );
  if (tagMatch) return tagMatch;

  // Fuzzy word contains
  const partial = INDIAN_FOODS_DATABASE.find(f => {
    const fLower = f.name.toLowerCase();
    const words = clean.split(/\s+/);
    return words.some(w => w.length > 3 && fLower.includes(w));
  });
  return partial;
}
